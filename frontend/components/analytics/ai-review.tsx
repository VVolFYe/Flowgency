"use client";

import { useEffect, useRef, useState } from "react";
import { api } from "@/lib/api";
import { isAnalyticsInsights, isAnalyticsList, type AnalyticsInsights, type AnalyticsListEntry } from "@/lib/contracts";

const LAST_RUN = "__last_run__";

type Review =
  | { status: "idle" }
  | { status: "loading" }
  | { status: "ready"; value: AnalyticsInsights }
  | { status: "error"; message: string };

function ReviewList({ title, items }: { title: string; items: string[] }) {
  if (items.length === 0) return null;
  return (
    <div>
      <p className="font-mono text-[10px] uppercase tracking-[.2em] text-[#667781]">{title}</p>
      <ul className="mt-2 list-disc space-y-1.5 pl-5 text-sm leading-6 text-[#c4d0d6]">
        {items.map((item, index) => <li key={index}>{item}</li>)}
      </ul>
    </div>
  );
}

/** Gemini review of the latest recorded run (+ fixed/adaptive pair) or one analytics entry. */
export function AiReview() {
  const [entries, setEntries] = useState<AnalyticsListEntry[] | null>(null);
  const [selectedId, setSelectedId] = useState(LAST_RUN);
  const [review, setReview] = useState<Review>({ status: "idle" });
  const pending = useRef<AbortController | null>(null);

  useEffect(() => {
    const controller = new AbortController();
    api.analyticsList(controller.signal)
      .then((value) => { if (isAnalyticsList(value)) setEntries(value); })
      .catch(() => { /* the last-run option still works without the analytics list */ });
    return () => { controller.abort(); pending.current?.abort(); };
  }, []);

  function select(id: string) {
    pending.current?.abort();
    setSelectedId(id);
    setReview({ status: "idle" });
  }

  async function generate() {
    pending.current?.abort();
    const controller = new AbortController();
    pending.current = controller;
    setReview({ status: "loading" });
    try {
      const value = await api.analyticsInsights(selectedId === LAST_RUN ? null : selectedId, AbortSignal.any([controller.signal, AbortSignal.timeout(35000)]));
      if (!isAnalyticsInsights(value)) throw new Error("The AI review response does not match the insights contract");
      if (!controller.signal.aborted) setReview({ status: "ready", value });
    } catch (reason) {
      if (!controller.signal.aborted) setReview({ status: "error", message: reason instanceof Error ? reason.message : "Unknown error" });
    }
  }

  return (
    <section className="surface mt-4 rounded-[24px] p-5 sm:p-6">
      <div className="flex flex-wrap items-end justify-between gap-4">
        <div>
          <p className="eyebrow">AI review</p>
          <h2 className="mt-1 text-base font-medium">Gemini analysis of recorded statistics</h2>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <label htmlFor="ai-review-dataset" className="text-xs text-[#788892]">Dataset</label>
          <select
            id="ai-review-dataset"
            value={selectedId}
            onChange={(event) => select(event.target.value)}
            className="rounded-lg border border-white/10 bg-[#10171c] px-2 py-1.5 text-sm text-[#dce5e9]"
          >
            <option value={LAST_RUN}>Last simulation run</option>
            {entries?.map((entry) => <option key={entry.id} value={entry.id}>{entry.label}</option>)}
          </select>
          <button
            type="button"
            onClick={generate}
            disabled={review.status === "loading"}
            className="rounded-lg border border-white/10 bg-white/[.06] px-3 py-1.5 text-sm text-[#dce5e9] hover:bg-white/[.1] disabled:opacity-50"
          >
            {review.status === "loading" ? "Generating…" : "Generate AI review"}
          </button>
        </div>
      </div>

      {review.status === "idle" && <p className="mt-5 text-sm text-[#81909a]">Choose a dataset and generate a review. The backend reads the statistics and sends a compact summary to Gemini.</p>}
      {review.status === "loading" && <p role="status" className="mt-5 text-sm text-[#81909a]">Asking Gemini… this can take up to 30 seconds.</p>}
      {review.status === "error" && <p role="alert" className="mt-5 text-sm text-[#ff7f86]">Could not generate the AI review: {review.message}</p>}
      {review.status === "ready" && (
        <div className="mt-5 space-y-5">
          <p className="text-sm leading-6 text-[#dce5e9]">{review.value.summary}</p>
          <div className="grid gap-5 lg:grid-cols-3">
            <ReviewList title="Key findings" items={review.value.key_findings} />
            <ReviewList title="Suggestions" items={review.value.suggestions} />
            <ReviewList title="Caveats" items={review.value.caveats} />
          </div>
          <p className="font-mono text-[10px] text-[#667781]">
            Generated by Gemini ({review.value.model}){review.value.cached ? " · cached" : ""}
            {review.value.source.kind === "latest_run" && ` · run ${review.value.source.id ?? "—"}${review.value.source.paired ? " with fixed/adaptive pair" : ""}`}
            {" "}· AI-generated text about simulation output; verify against the numbers.
          </p>
        </div>
      )}
    </section>
  );
}
